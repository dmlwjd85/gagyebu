const ws = XLSX.utils.aoa_to_sheet(sh);
XLSX.utils.sheet_add_aoa(ws, rows.map(([d, ...r]) => [new Date(d + 'T00:00:00'), ...r]), { origin: 'A4', cellDates: true });
ws['!cols'] = [{ wch: 12 }, { wch: 10 }, { wch: 20 }, { wch: 10 }];
for (let r = 3; r < 3 + rows.length; r++) { const c = ws[XLSX.utils.encode_cell({ r, c: 0 })]; if (c) c.z = 'yyyy-mm-dd'; }
const wb = XLSX.utils.book_new(); XLSX.utils.book_append_sheet(wb, ws, '이용내역');
writeFileSync('samples/신한카드_예시.xlsx', XLSX.write(wb, { type: 'buffer', bookType: 'xlsx' }));

